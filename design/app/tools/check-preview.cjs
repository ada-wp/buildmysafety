const {chromium}=require('playwright');
const {pathToFileURL}=require('url');
const path=require('path');
const assert=require('assert/strict');
const fs=require('fs');
const output=path.join(__dirname,'../qa-output');
fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:736,height:1120},deviceScaleFactor:1.5});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(__dirname,'../sick-day-journey.html')).href);
 const frame=page.frameLocator('iframe');
 await frame.locator('.ss-phone').waitFor();
 const inner=page.frames().find(f=>f!==page.mainFrame());
 await inner.evaluate(()=>document.fonts.ready);
 const phone=frame.locator('.ss-phone');
 assert.equal(await frame.locator('[data-card]').count(),3);
 await phone.screenshot({path:path.join(output,'01-suggestions.png')});
 await frame.locator('[data-card="shelf"] summary').click();
 assert.equal(await frame.locator('details[open]').count(),1);
 assert.match(await frame.locator('.ss-description').first().innerText(),/Start with what you already have/);
 await phone.screenshot({path:path.join(output,'02-expanded.png')});
 for(const id of ['shelf','checkin','delivery'])await frame.locator('[data-add="'+id+'"]').click();
 assert.match(await frame.locator('.ss-primary').innerText(),/3/);
 await frame.locator('[data-more]').click();
 assert.equal(await frame.locator('[data-card]').count(),3);
 assert.equal(await frame.locator('[data-card="shelf"]').count(),0);
 await frame.locator('.ss-primary[data-go="list"]').click();
 assert.equal(await frame.locator('.ss-list-task').count(),3);
 await phone.screenshot({path:path.join(output,'03-my-list.png')});
 await frame.locator('[data-complete="shelf"]').click();
 assert.equal(await phone.getAttribute('data-screen'),'growth');
 assert.match(await frame.locator('.ss-growth-tag').innerText(),/1 action completed/i);
 await phone.screenshot({path:path.join(output,'04-first-growth.png')});
 await frame.getByRole('button',{name:'Back to my list',exact:true}).click();
 assert.equal(await frame.locator('.ss-done').count(),1);
 await frame.locator('[data-complete="shelf"]').uncheck();
 assert.match(await frame.locator('.ss-progress-caption').innerText(),/1 small step/);
 await frame.locator('[data-complete="shelf"]').check();
 assert.equal(await phone.getAttribute('data-screen'),'list');
 assert.match(await frame.locator('.ss-progress-caption').innerText(),/1 small step/);
 await phone.screenshot({path:path.join(output,'05-completed-list.png')});
 await page.reload();
 await frame.locator('.ss-phone[data-screen="list"]').waitFor();
 assert.equal(await frame.locator('.ss-list-task').count(),3);
 assert.equal(await frame.locator('.ss-complete:checked').count(),1);
 await frame.getByRole('button',{name:'Ideas',exact:true}).click();
 await frame.getByRole('button',{name:'Edit selected concerns'}).click();
 for(const input of await frame.locator('[data-concern]').all())await input.uncheck();
 assert.equal(await frame.locator('[data-start]').isDisabled(),true);
 await frame.locator('textarea').fill('I want to prepare for being home sick.');
 assert.equal(await frame.locator('[data-start]').isDisabled(),false);
 await phone.screenshot({path:path.join(output,'06-concerns.png')});
 await frame.locator('[data-start]').click();
 assert.equal(await frame.locator('[data-card]').count(),3);
 for(const width of [320,393,736]){
  await page.setViewportSize({width,height:1120});
  const geometry=await inner.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth})).catch(async()=>{const f=page.frames().find(f=>f!==page.mainFrame());return await f.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));});
  assert.ok(geometry.scroll<=geometry.width+1,'Horizontal overflow at '+width);
 }
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,checks:['3 suggestions','expand brief description','save 3','next batch preserves saved','saved list','first completion grows elephant','undo preserves growth','re-completion does not re-award','reload restores preview state','manual-only concern input','320/393/736px layout','no JavaScript page errors']}));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
