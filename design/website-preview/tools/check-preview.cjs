const { chromium } = require('C:/Users/pweng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
(async()=>{
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.locator('h1').waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.waitForFunction(()=>document.querySelector('video')?.readyState>=3,null,{timeout:20000});
await page.screenshot({path:'artifacts/my-safety-desktop.png',fullPage:true});
const videoInfo=await page.locator('video').evaluateAll(v=>v.map(x=>({src:x.currentSrc,readyState:x.readyState,paused:x.paused})));
await page.getByRole('radio',{name:'My Body',exact:true}).click();
await page.getByRole('heading',{name:'Make room for your needs'}).waitFor();
await page.getByRole('radio',{name:'My Home',exact:true}).focus();
await page.keyboard.press('Space');
await page.getByRole('heading',{name:'A steadier place to come home to'}).waitFor();
await page.getByRole('button',{name:'See how it comes together'}).click();
await page.waitForTimeout(500);
const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
await page.waitForFunction(()=>document.querySelector('video')?.readyState>=3,null,{timeout:20000});
await page.screenshot({path:'artifacts/my-safety-mobile.png',fullPage:true});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.getByRole('radio',{name:'If I’m Out of Action',exact:true}).click();
await page.getByRole('heading',{name:'Let the everyday keep going'}).waitFor();
await page.emulateMedia({reducedMotion:'reduce'});
const reducedAnimation=await page.locator('h1').evaluate(x=>getComputedStyle(x).animationName);
const report={errors,videoInfo,desktopOverflow,mobileOverflow,reducedAnimation,sections:await page.locator('section').count(),title:await page.title()};
fs.writeFileSync('artifacts/qa-results.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
if(errors.length||desktopOverflow||mobileOverflow) process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
