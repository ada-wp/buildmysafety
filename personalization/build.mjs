import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Build-only dependencies and filesystem access. Commit the generated artifacts so
// the Worker can start without filesystem access, schema compilation or runtime eval.
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const sha256 = text => createHash('sha256').update(text).digest('hex');
const profileSchema = JSON.parse(read('../docs/contracts/user-profile-v0.schema.json'));
const outputSchema = JSON.parse(read('../docs/contracts/task-batch-v1.1.schema.json'));
const id = { type: 'string', minLength: 1, maxLength: 100, pattern: '^[a-z0-9][a-z0-9_-]*$' };
const date = { type: ['string', 'null'], format: 'date-time' };

// Internal input schemas have one source here; the exported runtime validators are
// generated from these definitions. Product profile/output schemas remain in docs.
const taskStateSchema = {
  type: 'object', additionalProperties: false,
  required: ['userId', 'actionKey', 'contentRef', 'shownAt', 'savedAt', 'removedAt', 'completedAt', 'likedAt', 'feedbackCode', 'feedbackAt'],
  properties: {
    userId: { type: 'string', minLength: 1, maxLength: 128 }, actionKey: id,
    contentRef: { type: 'string', minLength: 1, maxLength: 128 },
    shownAt: { type: 'string', format: 'date-time' }, savedAt: date, removedAt: date,
    completedAt: date, likedAt: date, feedbackAt: date,
    feedbackCode: { enum: [null, 'helpful', 'too_generic', 'too_much_effort', 'too_expensive', 'already_done', 'not_relevant_now'] }
  }
};
const requestSchema = {
  type: 'object', additionalProperties: false, required: ['topicId', 'concernIds'],
  properties: {
    topicId: { ...id, enum: profileSchema.properties.interests.items.enum },
    concernIds: { type: 'array', maxItems: 5, uniqueItems: true, items: id },
    note: { type: 'string', maxLength: 1000 },
    refineActionKey: id,
    country: { type: ['string', 'null'], pattern: '^[A-Z]{2}$' },
    maxMinutes: { type: ['integer', 'null'], minimum: 1, maximum: 120 },
    noSpend: { type: ['boolean', 'null'] },
    localSupport: { enum: ['available', 'unavailable', 'unknown'] }
  }
};

const promptFile = read('../docs/prompts/task-writer-v1.1-draft.md').replace(/\r\n/g, '\n');
const blocks = [...promptFile.matchAll(/```text\n([\s\S]*?)\n```/g)];
if (blocks.length !== 1) throw new Error('Expected one complete writer prompt.');
const instructions = blocks[0][1];
const promptHash = sha256(instructions);
const categoryFile = read('../docs/prompts/sick-care-category-v0.md').replace(/\r\n/g, '\n');
const categoryBlocks = [...categoryFile.matchAll(/```text\n([\s\S]*?)\n```/g)];
if (categoryBlocks.length !== 1) throw new Error('Expected one sick-care instruction block.');
const sickCareInstructions = categoryBlocks[0][1];
const sickCarePromptHash = sha256(sickCareInstructions);
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, lines: true } });
addFormats(ajv);
const schemas = { validProfile: profileSchema, validOutput: outputSchema, validTaskState: taskStateSchema, validRequest: requestSchema };
for (const [name, schema] of Object.entries(schemas)) ajv.addSchema(schema, name);

const banner = '// Generated by personalization/build.mjs. Do not edit; run npm run build.\n';
const files = new Map([
  ['contracts.mjs', banner + Object.entries({ profileSchema, outputSchema, instructions, promptHash, sickCareInstructions, sickCarePromptHash })
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`).join('\n\n') + '\n'],
  ['validators.cjs', banner + standaloneCode(ajv, Object.fromEntries(Object.keys(schemas).map(name => [name, name]))) + '\n']
]);
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node build.mjs [--check]');
if (!check) mkdirSync(new URL('./generated/', import.meta.url), { recursive: true });
for (const [filename, source] of files) {
  const target = new URL(`./generated/${filename}`, import.meta.url);
  const content = source.replace(/\r\n/g, '\n').trimEnd() + '\n';
  if (check) {
    let existing;
    try { existing = readFileSync(target, 'utf8').replace(/\r\n/g, '\n'); }
    catch { throw new Error(`Generated ${filename} is missing; run npm run build.`); }
    if (existing !== content) throw new Error(`Generated ${filename} is stale; run npm run build.`);
  } else writeFileSync(target, content, 'utf8');
}
console.log(`${check ? 'Verified' : 'Built'} static contracts and four validators; prompt sha256 ${promptHash}.`);
